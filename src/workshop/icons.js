const cache = new Map();
// The icon `name` as SVG text (12 pixels, drawn `size` across).
export function iconSvg(name, size = 12) {
  const k = `${name}:${size}`;
  if (cache.has(k)) return cache.get(k);
  const rows = I[name] || I.info;
  let rects = '';
  for (let y = 0; y < rows.length; y++) {
    const r = rows[y];
    let x = 0;
    while (x < r.length) {
      if (r[x] !== '#') {
        x++;
        continue;
      }
      let w = 1;
      while (r[x + w] === '#') w++;
      rects += `<rect x="${x}" y="${y}" width="${w}" height="1"/>`;
      x += w;
    }
  }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 12 12" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
  cache.set(k, svg);
  return svg;
}

