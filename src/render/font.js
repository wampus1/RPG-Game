const SHADES = {
  '░': (x, y) => (x + y * 2) % 4 === 0,
  '▒': (x, y) => (x + y) % 2 === 0,
  '▓': (x, y) => (x + y * 2) % 4 !== 0,
  '█': () => true,
  '▀': (x, y) => y < 4,
  '▄': (x, y) => y >= 4,
  '▌': (x) => x < 3,
  '▐': (x) => x >= 3,
};

export const CHARSET = [];
export const CHAR_INDEX = new Map();

function addChar(ch) {
  if (CHAR_INDEX.has(ch)) return;
  CHAR_INDEX.set(ch, CHARSET.length);
  CHARSET.push(ch);
}
for (const ch of Object.keys(G)) if (ch.length === 1) addChar(ch);
for (const ch of Object.keys(BOX)) addChar(ch);
for (const ch of Object.keys(DOUBLE)) addChar(ch);
for (const ch of Object.keys(SHADES)) addChar(ch);

export function glyphIndex(ch) {
  const i = CHAR_INDEX.get(ch);
  return i === undefined ? CHAR_INDEX.get('?') : i;
}

// Pixel bitmap (CHAR_W x CHAR_H booleans) for any supported character.
export function glyphBitmap(ch) {
  const bmp = new Uint8Array(CHAR_W * CHAR_H);
  const set = (x, y) => {
    if (x >= 0 && y >= 0 && x < CHAR_W && y < CHAR_H) bmp[y * CHAR_W + x] = 1;
  };
  if (G[ch] !== undefined) {
    const rows = G[ch].split('|');
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') set(x, y);
    });
  } else if (BOX[ch]) {
    const [u, d, l, r] = BOX[ch];
    const cx = 2;
    const cy = 3;
    if (u) for (let y = 0; y <= cy; y++) set(cx, y);
    if (d) for (let y = cy; y < CHAR_H; y++) set(cx, y);
    if (l) for (let x = 0; x <= cx; x++) set(x, cy);
    if (r) for (let x = cx; x < CHAR_W; x++) set(x, cy);
  } else if (DOUBLE[ch]) {
    DOUBLE[ch].split('|').forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') set(x, y);
    });
  } else if (SHADES[ch]) {
    for (let y = 0; y < CHAR_H; y++) for (let x = 0; x < CHAR_W; x++) if (SHADES[ch](x, y)) set(x, y);
  }
  return bmp;
}

// --- canvas atlas ---------------------------------------------------------
let atlas = null;
const tinted = new Map();
const COLS_IN_ATLAS = 32;

function buildAtlas() {
  const rows = Math.ceil(CHARSET.length / COLS_IN_ATLAS);
  const c = document.createElement('canvas');
  c.width = COLS_IN_ATLAS * CHAR_W;
  c.height = rows * CHAR_H;
  const ctx = c.getContext('2d');
  const img = ctx.createImageData(c.width, c.height);
  CHARSET.forEach((ch, i) => {
    const bmp = glyphBitmap(ch);
    const ox = (i % COLS_IN_ATLAS) * CHAR_W;
    const oy = Math.floor(i / COLS_IN_ATLAS) * CHAR_H;
    for (let y = 0; y < CHAR_H; y++) {
      for (let x = 0; x < CHAR_W; x++) {
        if (!bmp[y * CHAR_W + x]) continue;
        const p = ((oy + y) * c.width + ox + x) * 4;
        img.data[p] = img.data[p + 1] = img.data[p + 2] = img.data[p + 3] = 255;
      }
    }
  });
  ctx.putImageData(img, 0, 0);
  atlas = c;
}

export function fontAtlas(color) {
  if (!atlas) buildAtlas();
  let t = tinted.get(color);
  if (!t) {
    t = document.createElement('canvas');
    t.width = atlas.width;
    t.height = atlas.height;
    const ctx = t.getContext('2d');
    ctx.drawImage(atlas, 0, 0);
    ctx.globalCompositeOperation = 'source-in';
    ctx.fillStyle = color;
    ctx.fillRect(0, 0, t.width, t.height);
    tinted.set(color, t);
  }
  return t;
}

export function drawChar(ctx, ch, x, y, color) {
  const i = glyphIndex(ch);
  const a = fontAtlas(color);
  ctx.drawImage(a, (i % COLS_IN_ATLAS) * CHAR_W, Math.floor(i / COLS_IN_ATLAS) * CHAR_H, CHAR_W, CHAR_H, x, y, CHAR_W, CHAR_H);
}

// One glyph drawn bigger (whole multiples keep it crisp).
export function drawGlyph(ctx, ch, x, y, color, scale = 1) {
  const i = glyphIndex(ch);
  const a = fontAtlas(color);
  ctx.drawImage(a, (i % COLS_IN_ATLAS) * CHAR_W, Math.floor(i / COLS_IN_ATLAS) * CHAR_H, CHAR_W, CHAR_H, x, y, CHAR_W * scale, CHAR_H * scale);
}

// Free-positioned text (for world labels, bubbles, floating numbers).
export function drawText(ctx, str, x, y, color, shadow = null) {
  color ||= '#f4ecd8';
  if (shadow) {
    for (let i = 0; i < str.length; i++) drawChar(ctx, str[i], x + i * CHAR_W + 1, y + 1, shadow);
  }
  for (let i = 0; i < str.length; i++) drawChar(ctx, str[i], x + i * CHAR_W, y, color);
}

export function textWidth(str) {
  return str.length * CHAR_W;
}
